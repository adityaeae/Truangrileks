<?php

namespace App\Http\Controllers;

use Illuminate\Http\RedirectResponse;
use Illuminate\Http\Request;

class NotificationController extends Controller
{
    public function markRead(Request $request, string $notificationId): RedirectResponse
    {
        // Query through the authenticated user's relationship so another user's
        // notification cannot be read or marked as read by changing the ID.
        $notification = $request->user()
            ->notifications()
            ->whereKey($notificationId)
            ->firstOrFail();

        $notification->markAsRead();

        return redirect()->to($this->internalDestination($notification->data['url'] ?? null));
    }

    public function markAllRead(Request $request): RedirectResponse
    {
        $request->user()->unreadNotifications()->update([
            'read_at' => now(),
        ]);

        return back()->with('status', 'Semua notifikasi telah ditandai dibaca.');
    }

    private function internalDestination(mixed $destination): string
    {
        $fallback = route('dashboard');

        if (! is_string($destination) || $destination === '') {
            return $fallback;
        }

        $target = parse_url($destination);
        $application = parse_url($fallback);

        if (! is_array($target) || ! is_array($application)) {
            return $fallback;
        }

        // Notification URLs are generated by this application. Still verify the
        // origin before redirecting so a manipulated payload cannot cause an
        // external redirect.
        if (($target['scheme'] ?? null) !== ($application['scheme'] ?? null)
            || ($target['host'] ?? null) !== ($application['host'] ?? null)
            || ($target['port'] ?? null) !== ($application['port'] ?? null)
            || ! isset($target['path'])
            || ! str_starts_with($target['path'], '/')) {
            return $fallback;
        }

        return $destination;
    }
}
